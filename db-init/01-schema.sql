-- EMS Database Schema
-- Created for Event Management System

SET NAMES utf8mb4;
SET CHARACTER SET utf8mb4;
SET character_set_connection = utf8mb4;

CREATE DATABASE IF NOT EXISTS ems_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ems_db;

-- Organizations table
CREATE TABLE IF NOT EXISTS organizations (
    idOrg INT AUTO_INCREMENT PRIMARY KEY,
    orgName VARCHAR(255) NOT NULL,
    orgType VARCHAR(100) DEFAULT NULL,
    description TEXT,
    createdDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Users table
CREATE TABLE IF NOT EXISTS users (
    idUser INT AUTO_INCREMENT PRIMARY KEY,
    fullName VARCHAR(255) NOT NULL,
    gender VARCHAR(10) DEFAULT NULL,
    dateOfBirth DATE DEFAULT NULL,
    phoneNumber VARCHAR(20) DEFAULT NULL,
    studentCode VARCHAR(50) DEFAULT NULL,
    classCode VARCHAR(50) DEFAULT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    createdDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Clubs table
CREATE TABLE IF NOT EXISTS clubs (
    idClub INT AUTO_INCREMENT PRIMARY KEY,
    clubName VARCHAR(255) NOT NULL,
    shortName VARCHAR(50) DEFAULT NULL,
    description TEXT,
    leaderName VARCHAR(255) DEFAULT NULL,
    leaderPhone VARCHAR(20) DEFAULT NULL,
    leaderCode VARCHAR(50) DEFAULT NULL,
    idOrg INT NOT NULL,
    idUser INT NOT NULL,
    createdDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (idOrg) REFERENCES organizations(idOrg) ON DELETE RESTRICT,
    FOREIGN KEY (idUser) REFERENCES users(idUser) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Events table
CREATE TABLE IF NOT EXISTS events (
    idEvent INT AUTO_INCREMENT PRIMARY KEY,
    nameEvent VARCHAR(255) NOT NULL,
    description TEXT,
    image VARCHAR(255) DEFAULT NULL,
    startDate DATETIME NOT NULL,
    endDate DATETIME NOT NULL,
    location VARCHAR(255) DEFAULT NULL,
    registrationDeadline DATETIME NOT NULL,
    maxRegistration INT DEFAULT NULL,
    numberOfRegistration INT DEFAULT 0,
    status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    rejectionReason TEXT,
    approvedBy INT DEFAULT NULL,
    approvedDate DATETIME DEFAULT NULL,
    isDeleted TINYINT(1) DEFAULT 0,
    createdDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    idClub INT NOT NULL,
    FOREIGN KEY (approvedBy) REFERENCES users(idUser) ON DELETE SET NULL,
    FOREIGN KEY (idClub) REFERENCES clubs(idClub) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Registrations table
CREATE TABLE IF NOT EXISTS registrations (
    idRegistration INT AUTO_INCREMENT PRIMARY KEY,
    registrationDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(255) NOT NULL DEFAULT 'REGISTERED',
    cancelledDate DATETIME DEFAULT NULL,
    idEvent INT NOT NULL,
    idStudent INT NOT NULL,
    FOREIGN KEY (idEvent) REFERENCES events(idEvent) ON DELETE CASCADE,
    FOREIGN KEY (idStudent) REFERENCES users(idUser) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Notifications table
CREATE TABLE IF NOT EXISTS notifications (
    idNotification INT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    type VARCHAR(255) NOT NULL,
    createdDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isRead TINYINT(1) DEFAULT 0,
    idUser INT NOT NULL,
    FOREIGN KEY (idUser) REFERENCES users(idUser) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
